import { mkdir, readFile, writeFile } from "node:fs/promises";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import addFormats from "ajv-formats";

const schema = JSON.parse(await readFile(new URL(
  "../../../spec/v4.0/schemas/course-v3.schema.json", import.meta.url,
), "utf8"));
const output = new URL("../src/contract/generated/", import.meta.url);

function compiler(allErrors) {
  const ajv = new Ajv2020({
    allErrors,
    inlineRefs: false,
    ownProperties: true,
    // The v3 conditional subschemas inherit types from their enclosing schema.
    strictTypes: false,
    code: { source: true, esm: true, lines: true },
  });
  addFormats(ajv, ["date-time", "uri"]);
  return ajv;
}

// Ajv emits ESM exports but loads its runtime helpers with require(). Turn
// those static helper references into imports so the Worker needs no Node shim.
function esm(source) {
  const imports = new Map();
  const body = source.replace(/\brequire\("([\w@/-]+)"\)(\.default)?/g, (_, path, defaultExport) => {
    if (!imports.has(path)) imports.set(path, `helper${imports.size}`);
    const name = imports.get(path);
    // Node and bundlers differ on whether a CommonJS default is unwrapped.
    return defaultExport ? `(${name}.default ?? ${name})` : name;
  });
  if (/\brequire\s*\(|\beval\s*\(|\bnew\s+Function\s*\(/.test(body)) {
    throw new Error("Unexpected runtime loading or code generation in standalone validator");
  }
  const headers = [...imports].map(([path, name]) => `import ${name} from "${path}.js";`);
  return ["// Generated by scripts/compile-schemas.mjs.", ...headers, body].join("\n");
}

// A second set of validators collects errors one schema node at a time.
// The caller can stop at its diagnostic budget instead of asking Ajv to
// allocate every error in the manifest. Acceptance uses the full schema.
const diagnostics = compiler(true);
const diagnosticNodes = {};
function addDiagnosticNode(shape, pointer) {
  const { $id, $schema, $defs, additionalProperties, items, properties, ...local } = shape;
  if (items && !items.$ref && !items.oneOf && !items.properties) local.items = items;
  if (items?.properties) addDiagnosticNode(items, `${pointer}/items`);
  if (properties) {
    local.properties = Object.fromEntries(Object.entries(properties).map(([key, child]) => {
      if (!child.items && !child.properties) return [key, child];
      addDiagnosticNode(child, `${pointer}/properties/${key}`);
      return [key, true];
    }));
  }
  const name = `node${Object.keys(diagnosticNodes).length}`;
  const key = `urn:lectale:diagnostic:${name}`;
  diagnostics.addSchema(local, key);
  diagnosticNodes[name] = { key, pointer };
}

addDiagnosticNode(schema, "#");
for (const [name, shape] of Object.entries(schema.$defs)) {
  addDiagnosticNode(shape, `#/$defs/${name}`);
}

const full = compiler(false);
const local = standaloneCode(diagnostics, Object.fromEntries(
  Object.entries(diagnosticNodes).map(([name, entry]) => [name, entry.key]),
));
const byPointer = Object.entries(diagnosticNodes).map(([name, { pointer }]) =>
  `  ${JSON.stringify(pointer)}: ${name},`);

await mkdir(output, { recursive: true });
await Promise.all([
  writeFile(new URL("course-v3.validate.js", output), esm(standaloneCode(full, full.compile(schema)))),
  writeFile(new URL("course-v3.diagnostics.js", output), esm(
    `${local}\nexport default {\n${byPointer.join("\n")}\n};\n`,
  )),
]);
